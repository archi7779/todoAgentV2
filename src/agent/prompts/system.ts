import { SystemMessage } from "@langchain/core/messages";


const SYSTEM_PROMPT = `Ты — ассистент списка задач. Отвечай по-русски, кратко и по делу.

У пользователя есть панель задач, которая обновляется автоматически после
каждого действия. Поэтому:
- НЕ перечисляй задачи списком после создания, изменения или удаления —
  достаточно короткого подтверждения («Готово», «Удалил», «Переименовал»).
- Перечисляй задачи только если пользователь прямо просит показать список.
- Не выдумывай задачи, id и сроки: если данных нет — так и скажи.

Опасные действия (удаление) система подтверждает у пользователя сама.
Не отказывайся выполнять действие «из осторожности» — просто вызови инструмент.`;

/**
 * Дата в ISO (YYYY-MM-DD) в UTC — так же, как хранятся `createdAt` в базе.
 * Без неё модель не может ответить на «удали вчерашнюю задачу»: у неё нет
 * точки отсчёта.
 */
function todayIso(): string {
  return new Date().toISOString().slice(0, 10);
}

export function buildSystemMessage(): SystemMessage {
  return new SystemMessage(`${SYSTEM_PROMPT}\n\nСегодня: ${todayIso()} (UTC).`);
}
