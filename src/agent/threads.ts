/**
 * Идентификатор треда LangGraph.
 *
 * Сейчас действует правило «1 пользователь = 1 чат = 1 тред», поэтому thread_id
 * детерминированно выводится из userId и НЕ приходит от клиента. Если бы клиент
 * присылал его сам, любой авторизованный пользователь мог бы подставить чужой
 * id и продолжить чужой диалог: checkpointer отдаёт state строго по thread_id
 * и про владельца ничего не знает.
 *
 * Когда появятся несколько чатов, сюда придёт chatId из БД. Владение всё равно
 * должно проверяться на сервере (chat.userId === session.user.id), а не на
 * клиенте.
 */
export function getMainThreadId(userId: string): string {
  return `${userId}:main`;
}
