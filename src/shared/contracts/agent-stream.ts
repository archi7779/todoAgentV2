/**
 * Контракт SSE-потока агента.
 *
 * Один источник правды для обеих сторон:
 *   - сервер отдаёт эти события (`app/api/protected/agent-stream/route.ts`);
 *   - клиент их разбирает (`lib/hooks/use-agent-stream.ts`).
 *
 * Поэтому файл живёт в `shared/contracts`, а не рядом с роутом: клиент не должен
 * импортировать ничего из `app/api/**` (там может быть server-only код).
 *
 * Инвариант потока: сервер обязан закончить поток одним из терминальных событий —
 * `done` | `interrupt` | `error`. Если поток закрылся без них, клиент обязан сам
 * пометить прогон как сломанный (иначе UI зависнет в «Думаю…»).
 */
export type AgentStreamEvent =
  /** Кусок текста ответа. Склеивается на клиенте по порядку прихода. */
  | { type: "token"; content: string }
  /** Кусок «размышлений» модели. Отдельно от текста, чтобы UI мог свернуть их. */
  | { type: "reasoning"; content: string }
  /** Модель запросила инструмент. `node` — узел графа, который это вернул. */
  | { type: "tool_call"; node: string; tool: string; args: unknown }
  /** Узел графа закончил шаг. Отдельного `node_start` нет — сервер его не шлёт. */
  | { type: "node_end"; node: string }
  /** HITL: прогон встал на паузу и ждёт ответа человека. */
  | { type: "interrupt"; interrupt: unknown }
  /** Успешный финал: прогон завершён. */
  | { type: "done"; message: string }
  /** Ошибка ПОСЛЕ старта стрима: статус HTTP уже не поменять, сообщаем событием. */
  | { type: "error"; error: string; message?: string }
     /** инфа о количестве токенов. */
  | { type: "usage"; tokenUsage: number }
